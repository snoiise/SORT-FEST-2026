@dataclass
class Submission:
    id: str
    metadata: dict
    source: Path


@dataclass
class CompiledSubmission:
    submission: Submission
    function_name: str


@dataclass
class FailedSubmission:
    submission: Submission
    error: str

def safe_name(value: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9_]", "_", value)

    if not value:
        value = "submission"

    if value[0].isdigit():
        value = "_" + value

    return value


def c_string(value) -> str:
    return (
        str(value)
        .replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )


def clean_build_directory():
    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR)

    NIM_DIR.mkdir(parents=True)
    GENERATED_DIR.mkdir(parents=True)
    NIMCACHE_DIR.mkdir(parents=True)

def load_submissions():
    submissions = []

    if not SUBMISSIONS_DIR.exists():
        print(f"ERROR: submission directory does not exist:")
        print(f"  {SUBMISSIONS_DIR}")
        return submissions

    for folder in sorted(SUBMISSIONS_DIR.iterdir()):

        if not folder.is_dir():
            continue

        json_path = folder / f"{folder.name}.json"

        if not json_path.exists():
            print(f"WARNING: missing metadata file: {json_path}")
            continue

        try:
            with json_path.open("r", encoding="utf-8") as file:
                metadata = json.load(file)

        except Exception as error:
            print(f"WARNING: failed to read {json_path}")
            print(f"  {error}")
            continue

        code_name = metadata.get("code")

        if not isinstance(code_name, str):
            print(f"WARNING: {json_path} has no valid 'code' field")
            continue

        source = folder / code_name

        if not source.exists():
            print(f"WARNING: source file does not exist: {source}")
            continue

        submissions.append(
            Submission(
                id=folder.name,
                metadata=metadata.get("metadata", {}),
                source=source,
            )
        )

    return submissions

def generate_combined_nim(submissions):

    lines = [
        "# Generated by Sort Fest 2026",
        "",
    ]

    valid = []

    for submission in submissions:

        function_name = (
            "sortfest_impl_"
            + safe_name(submission.id)
        )

        bridge_name = (
            "sortfest_"
            + safe_name(submission.id)
        )

        try:
            source = submission.source.read_text(
                encoding="utf-8"
            )

        except Exception as error:
            valid.append(
                FailedSubmission(
                    submission=submission,
                    error=str(error),
                )
            )
            continue

        renamed, count = re.subn(
            r"(\bproc\s+)sort(\s*\()",
            rf"\1{function_name}\2",
            source,
            count=1,
        )

        if count == 0:
            valid.append(
                FailedSubmission(
                    submission=submission,
                    error=(
                        "Could not find a procedure named "
                        "'sort'."
                    ),
                )
            )
            continue

        lines.append(
            f"# {submission.metadata.get('name', submission.id)}"
        )
        lines.append("")

        lines.append(renamed.rstrip())
        lines.append("")

        # C-compatible bridge.
        lines.append(
            f'proc sortfest_bridge_{safe_name(submission.id)}('
        )
        lines.append(
            "    data: ptr UncheckedArray[int],"
        )
        lines.append(
            "    length: csize_t"
        )
        lines.append(
            f') {{.exportc: "{bridge_name}", cdecl.}} ='
        )

        lines.append(
            "    var values = newSeq[int](int(length))"
        )

        lines.append(
            "    for i in 0..<int(length):"
        )

        lines.append(
            "        values[i] = data[i]"
        )

        lines.append("")

        lines.append(
            f"    {function_name}(values)"
        )

        lines.append("")

        lines.append(
            "    for i in 0..<int(length):"
        )

        lines.append(
            "        data[i] = values[i]"
        )

        lines.append("")

        valid.append(
            CompiledSubmission(
                submission=submission,
                function_name=bridge_name,
            )
        )

    COMBINED_NIM.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    return valid

def compile_nim():

    print()
    print("Generating C from Nim...")

    command = [
        str(NIM_EXE),
        "c",
        "--app:lib",
        "--compileOnly",
        "--cc:gcc",
        "--opt:speed",
        "--nimcache:" + str(NIMCACHE_DIR),
        str(COMBINED_NIM),
    ]

    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:

        print()
        print("Nim compilation failed:")
        print(result.stdout)
        print(result.stderr)

        return None

    generated_main = NIMCACHE_DIR / "@mcombined.nim.c"

    if not generated_main.exists():

        print()
        print("ERROR: Nim compiled successfully, but")
        print("the generated C file was not found.")
        print()
        print("Expected:")
        print(generated_main)

        return None

    return generated_main

def generate_benchmark_c(compiled, generated_nim_c):
    embedded_c = generated_nim_c.read_text(
        encoding="utf-8"
    )

    submissions = []

    for item in compiled:
        name = item.submission.metadata.get(
            "name",
            item.submission.id,
        )

        author = item.submission.metadata.get(
            "author",
            "Unknown",
        )

        submissions.append(
            f'''    {{
        "{c_string(name)}",
        "{c_string(author)}",
        {item.function_name}
    }}'''
        )

    submission_table = ",\n".join(submissions)

    benchmark_c = f'''\
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

{embedded_c}

typedef void (*SortFunction)(NI *, size_t);

typedef struct {{
    const char *name;
    const char *author;
    SortFunction sort;
}} Submission;

static uint64_t rng_state = 0x123456789abcdefULL;

static uint64_t rng_next(void)
{{
    rng_state ^= rng_state << 13;
    rng_state ^= rng_state >> 7;
    rng_state ^= rng_state << 17;
    return rng_state;
}}

static NI random_value(void)
{{
    return (NI)(rng_next() % 1000000);
}}

static void generate_random(NI *data, size_t n)
{{
    for (size_t i = 0; i < n; i++)
        data[i] = random_value();
}}

static void generate_sorted(NI *data, size_t n)
{{
    for (size_t i = 0; i < n; i++)
        data[i] = (NI)i;
}}

static void generate_reversed(NI *data, size_t n)
{{
    for (size_t i = 0; i < n; i++)
        data[i] = (NI)(n - i);
}}

static void generate_duplicates(NI *data, size_t n)
{{
    for (size_t i = 0; i < n; i++)
        data[i] = (NI)(rng_next() % 16);
}}

static void generate_nearly_sorted(NI *data, size_t n)
{{
    for (size_t i = 0; i < n; i++)
        data[i] = (NI)i;

    size_t swaps = n / 100;

    if (swaps < 1)
        swaps = 1;

    for (size_t i = 0; i < swaps; i++)
    {{
        size_t a = rng_next() % n;
        size_t b = rng_next() % n;

        NI temp = data[a];
        data[a] = data[b];
        data[b] = temp;
    }}
}}

static int verify_sorted(const NI *data, size_t n)
{{
    for (size_t i = 1; i < n; i++)
    {{
        if (data[i - 1] > data[i])
            return 0;
    }}

    return 1;
}}

static void benchmark(
    const Submission *submission,
    const char *scenario,
    void (*generate)(NI *, size_t),
    size_t size
)
{{
    NI *original = malloc(size * sizeof(NI));
    NI *data = malloc(size * sizeof(NI));

    if (!original || !data)
    {{
        fprintf(
            stderr,
            "Allocation failed for %zu elements\\n",
            size
        );

        free(original);
        free(data);
        return;
    }}

    generate(original, size);

    memcpy(
        data,
        original,
        size * sizeof(NI)
    );

    clock_t start = clock();

    submission->sort(
        data,
        size
    );

    clock_t end = clock();

    double elapsed =
        (double)(end - start) / CLOCKS_PER_SEC;

    int valid = verify_sorted(
        data,
        size
    );

    printf(
        "%s,%s,%s,%zu,%.9f,%s\\n",
        submission->name,
        submission->author,
        scenario,
        size,
        elapsed,
        valid ? "OK" : "FAILED"
    );

    free(original);
    free(data);
}}

int main(void)
{{
    NimMain();

    static Submission submissions[] =
    {{
{submission_table}
    }};

    static const size_t sizes[] =
    {{
        1000,
        10000,
        100000,
        1000000
    }};

    static const struct
    {{
        const char *name;
        void (*generate)(NI *, size_t);
    }} scenarios[] =
    {{
        {{
            "random",
            generate_random
        }},
        {{
            "sorted",
            generate_sorted
        }},
        {{
            "reversed",
            generate_reversed
        }},
        {{
            "duplicates",
            generate_duplicates
        }},
        {{
            "nearly_sorted",
            generate_nearly_sorted
        }}
    }};

    size_t submission_count =
        sizeof(submissions) / sizeof(submissions[0]);

    size_t size_count =
        sizeof(sizes) / sizeof(sizes[0]);

    size_t scenario_count =
        sizeof(scenarios) / sizeof(scenarios[0]);

    printf(
        "algorithm,author,scenario,size,time,result\\n"
    );

    for (size_t s = 0; s < submission_count; s++)
    {{
        for (size_t c = 0; c < scenario_count; c++)
        {{
            for (size_t z = 0; z < size_count; z++)
            {{
                benchmark(
                    &submissions[s],
                    scenarios[c].name,
                    scenarios[c].generate,
                    sizes[z]
                );
            }}
        }}
    }}

    return 0;
}}
'''

    BENCHMARK_C.write_text(
        benchmark_c,
        encoding="utf-8"
    )

def compile_benchmark():
    print()
    print("Compiling benchmark...")

    nim_lib = NIM_EXE.parent.parent / "lib"

    nim_c_files = sorted(
        NIMCACHE_DIR.glob("*.nim.c")
    )

    runtime_c_files = [
        path
        for path in nim_c_files
        if path.name != "@mcombined.nim.c"
    ]

    command = [
        str(GCC_EXE),
        "-O3",
        "-w",
        "-fno-strict-aliasing",
        f"-I{nim_lib}",
        str(BENCHMARK_C),
        *[str(path) for path in runtime_c_files],
        "-lpthread",
        "-o",
        str(BENCHMARK_EXE),
    ]

    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        print()
        print("GCC compilation failed:")
        print(result.stdout)
        print(result.stderr)
        return False

    if not BENCHMARK_EXE.exists():
        print()
        print("GCC reported success, but benchmark.exe was not created.")
        print("Expected:", BENCHMARK_EXE.resolve())
        return False

    print("Benchmark compiled")

    return True

def run_benchmark():
    print()
    print("Running benchmark...")

    exe = BENCHMARK_EXE.resolve()

    if not exe.exists():
        print(f"Benchmark executable not found: {exe}")
        return False

    result = subprocess.run(
        [str(exe)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )

    if result.returncode != 0:
        print()
        print("Benchmark failed:")
        print(result.stdout)
        print(result.stderr)
        return False

    RESULTS_FILE.write_text(
        result.stdout,
        encoding="utf-8",
    )

    print(result.stdout)

    print()
    print(f"Results saved to: {RESULTS_FILE}")

    return True

def main():
    print("SORT FEST 2026 BENCHMARKING")

    if not NIM_EXE.exists():

        print()
        print("ERROR: Nim compiler not found:")
        print(NIM_EXE)

        return 1

    if not GCC_EXE.exists():

        print()
        print("ERROR: GCC compiler not found:")
        print(GCC_EXE)

        return 1
    
    clean_build_directory()

    submissions = load_submissions()

    print()
    print(f"Found {len(submissions)} submission(s).")

    if not submissions:

        print()
        print("No submissions found.")

        return 1

    print()
    print("Preparing submissions...")

    prepared = generate_combined_nim(
        submissions
    )

    successful = [
        item
        for item in prepared
        if isinstance(item, CompiledSubmission)
    ]

    failed = [
        item
        for item in prepared
        if isinstance(item, FailedSubmission)
    ]

    if failed:

        print()
        print("Failed submissions:")

        for item in failed:

            name = item.submission.metadata.get(
                "name",
                item.submission.id,
            )

            print(f"{name}")
            print(f"{item.error}")

    if not successful:

        print()
        print("No valid submissions.")

        return 1

    print()
    print("Compiling submissions...")

    generated_nim_c = compile_nim()

    if generated_nim_c is None:
        return 1

    for item in successful:

        name = item.submission.metadata.get(
            "name",
            item.submission.id,
        )

        print(f"{name}")

    print()
    print("Generating benchmark.c...")

    try:

        generate_benchmark_c(
            successful,
            generated_nim_c,
        )

    except Exception as error:

        print()
        print("Failed to generate benchmark.c:")
        print(error)

        return 1

    if not compile_benchmark():
        return 1
    
    if not run_benchmark():
        return 1

    print()
    print("Benchmark complete.")

    return 0


if __name__ == "__main__":
    sys.exit(main())